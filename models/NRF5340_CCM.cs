//
// NRF5340_CCM_AAR — nRF5340 network-core AES CCM cipher + accelerated address
// resolver, one register page at 0x4100E000, IRQ 14.
//
// CCM and AAR are two SVD peripherals sharing one page and one hardware block
// ("cannot be used simultaneously" — nRF5340 PS); their register offsets
// overlap with different meanings (0x000 TASKS_KSGEN/TASKS_START, 0x100
// ENDKSGEN/END, 0x400 MICSTATUS/STATUS, 0x504 MODE/NIRK, 0x508 CNFPTR/IRKPTR,
// 0x510 OUTPTR/ADDRPTR, ...). This container implements the union register
// map verbatim from svd/nrf5340_network.svd (hal_nordic 9784731…, see
// reference/nrf5340_regs.rs net::ccm / net::aar): shared storage where offsets
// collide (they are the same flops on silicon), interpretation chosen by
// ENABLE at task time (2 = CCM, 3 = AAR). AAR behaviour is delegated to the
// cooperating engine in models/NRF5340_AAR.cs.
//
// CCM behaviour per the nRF5340 PS CCM chapter
// (https://docs.nordicsemi.com/bundle/ps_nrf5340/page/ccm.html) and the
// Bluetooth Core Specification AES-CCM (Vol 6 Part E): real AES-CCM (L=2,
// M=4) built from the AES-ECB primitive.
//   CNFPTR structure: KEY[16] (big-endian, used directly as the AES key),
//     PKTCTR[5] at offset 16 (39 bits, octet 0 = LSB), direction bit at
//     offset 24 bit 0, IV[8] at offset 25.
//   Nonce: counter bytes 0..3, byte 4 = (PKTCTR bits 38:32) | direction<<7,
//     then the 8 IV bytes — exactly the octet string the Bluetooth spec
//     prescribes. Verified against the Core spec sample data
//     (Vol 6 Part C: SK 0x99AD1B52...C666, IV 0xDEAFBABEBADCAB24,
//     START_ENC_RSP1 payload 06 -> ciphertext 9F, MIC CD A7 F4 48).
//   AAD: one byte, packet header & HEADERMASK (reset 0xE3).
//   Packet layout at INPTR/OUTPTR: [header][length][RFU/S1][payload...];
//     encryption writes length+4 and appends the 4-byte MIC; decryption
//     strips it and updates MICSTATUS. Zero-length packets pass through
//     unmodified (and always pass the MIC check on decryption); decryption
//     of length 1..4 fails the MIC check (PS).
//   MODE: bit 0 encrypt/decrypt, DATARATE[17:16] and LENGTH[24] per the SVD;
//     LENGTH=Default caps the payload at 27 bytes, Extended at MAXPACKETSIZE.
//   Timing: on hardware KSGEN/CRYPT run synchronised to the radio data rate;
//     here both complete synchronously in virtual time (deterministic, and
//     always "in time" for consumers that poll or use the ENDKSGEN_CRYPT
//     short). SCRATCHPTR is bounds-ignored (scratch contents are never
//     architecturally visible). EVENTS_ERROR (a RAM-port collision condition
//     on silicon) is never generated by this model.
//   TASKS_RATEOVERRIDE / RATEOVERRIDE: stored; no behavioural effect (data
//     rate does not exist in this model) — logged as UNSUPPORTED once.
//
// Fault injection (monitor-settable, default off):
//   FaultMicError       — the next decryption reports MICSTATUS=CheckFailed
//   FaultDropInterrupt  — swallow the next rising IRQ edge
//
using System;

using Antmicro.Renode.Core;
using Antmicro.Renode.Core.Structure.Registers;
using Antmicro.Renode.Logging;
using Antmicro.Renode.Peripherals.Bus;
using Antmicro.Renode.Peripherals.Timers;
using Antmicro.Renode.Time;
using Antmicro.Renode.Utilities.Crypto;

namespace Antmicro.Renode.Peripherals.Miscellaneous
{
    public class NRF5340_CCM_AAR : BasicDoubleWordPeripheral, IKnownSize
    {
        public NRF5340_CCM_AAR(IMachine machine, NRF5340_DPPIC dppic = null) : base(machine)
        {
            IRQ = new GPIO();
            aar = new NRF5340_AAR(this);

            subscribeKsgenOrStart = new DPPISubscribeEndpoint(dppic, this, "KSGEN/START", () => TaskKsgenOrAarStart());
            subscribeCrypt = new DPPISubscribeEndpoint(dppic, this, "CRYPT", TaskCrypt);
            subscribeStop = new DPPISubscribeEndpoint(dppic, this, "STOP", TaskStop);
            subscribeRateOverride = new DPPISubscribeEndpoint(dppic, this, "RATEOVERRIDE", TaskRateOverride);
            publishEvent = new DPPIPublishEndpoint[EventCount];
            publishEvent[0] = new DPPIPublishEndpoint(dppic, this, "ENDKSGEN/END");
            publishEvent[1] = new DPPIPublishEndpoint(dppic, this, "ENDCRYPT/RESOLVED");
            publishEvent[2] = new DPPIPublishEndpoint(dppic, this, "ERROR/NOTRESOLVED");

            aarTimer = new LimitTimer(machine.ClockSource, TimerFrequency, this, "aarResolve",
                limit: 1, direction: Direction.Ascending, enabled: false,
                workMode: WorkMode.OneShot, eventEnabled: true);
            aarTimer.LimitReached += CompleteAarResolution;

            DefineRegisters();
            Reset();
        }

        public override void Reset()
        {
            base.Reset();
            eventPending = 0;
            interruptEnable = 0;
            micStatusOk = false;
            aarStatus = 0;
            aarPendingValid = false;
            rateOverrideWarned = false;
            aarTimer.Enabled = false;
            subscribeKsgenOrStart.Reset();
            subscribeCrypt.Reset();
            subscribeStop.Reset();
            subscribeRateOverride.Reset();
            foreach(var endpoint in publishEvent)
            {
                endpoint.Reset();
            }
            IRQ.Unset();
        }

        public long Size => 0x1000;

        public GPIO IRQ { get; }

        // Force the next decryption's MIC check to fail.
        public bool FaultMicError { get; set; }
        // Swallow the next rising IRQ edge.
        public bool FaultDropInterrupt { get; set; }

        public override uint ReadDoubleWord(long offset)
        {
            if(RegistersCollection.TryRead(offset, out var result))
            {
                return result;
            }
            NRF5340_DPPIC.LogUnimplementedAccess(this, machine, "R", offset, 0);
            return 0;
        }

        public override void WriteDoubleWord(long offset, uint value)
        {
            if(!RegistersCollection.TryWrite(offset, value))
            {
                NRF5340_DPPIC.LogUnimplementedAccess(this, machine, "W", offset, value);
            }
        }

        private void DefineRegisters()
        {
            Registers.TasksKsgen.Define(this)
                .WithFlag(0, FieldMode.Write, name: "TASKS_KSGEN/TASKS_START",
                    writeCallback: (_, value) => { if(value) TaskKsgenOrAarStart(); })
                .WithReservedBits(1, 31);

            Registers.TasksCrypt.Define(this)
                .WithFlag(0, FieldMode.Write, name: "TASKS_CRYPT",
                    writeCallback: (_, value) => { if(value) TaskCrypt(); })
                .WithReservedBits(1, 31);

            Registers.TasksStop.Define(this)
                .WithFlag(0, FieldMode.Write, name: "TASKS_STOP",
                    writeCallback: (_, value) => { if(value) TaskStop(); })
                .WithReservedBits(1, 31);

            Registers.TasksRateOverride.Define(this)
                .WithFlag(0, FieldMode.Write, name: "TASKS_RATEOVERRIDE",
                    writeCallback: (_, value) => { if(value) TaskRateOverride(); })
                .WithReservedBits(1, 31);

            DefineSubscribe(Registers.SubscribeKsgen, "SUBSCRIBE_KSGEN/START", subscribeKsgenOrStart);
            DefineSubscribe(Registers.SubscribeCrypt, "SUBSCRIBE_CRYPT", subscribeCrypt);
            DefineSubscribe(Registers.SubscribeStop, "SUBSCRIBE_STOP", subscribeStop);
            DefineSubscribe(Registers.SubscribeRateOverride, "SUBSCRIBE_RATEOVERRIDE", subscribeRateOverride);

            for(var i = 0; i < EventCount; i++)
            {
                var bit = i;
                ((Registers)(0x100 + 4 * i)).Define(this, name: EventNames[i])
                    .WithFlag(0, name: EventNames[i],
                        valueProviderCallback: _ => (eventPending & (1u << bit)) != 0,
                        writeCallback: (_, value) =>
                        {
                            if(value)
                            {
                                eventPending |= 1u << bit;
                            }
                            else
                            {
                                eventPending &= ~(1u << bit);
                            }
                            UpdateInterrupts();
                        })
                    .WithReservedBits(1, 31);
                ((Registers)(0x180 + 4 * i)).Define(this, name: $"PUBLISH_{EventNames[i]}")
                    .WithValueField(0, 32, name: $"PUBLISH_{EventNames[i]}",
                        valueProviderCallback: _ => publishEvent[bit].RegisterValue,
                        writeCallback: (_, value) => publishEvent[bit].RegisterValue = (uint)value);
            }

            Registers.Shorts.Define(this)
                .WithFlag(0, out shortEndKsgenCrypt, name: "ENDKSGEN_CRYPT")
                .WithReservedBits(1, 31);

            Registers.IntenSet.Define(this)
                .WithValueField(0, 32, name: "INTENSET",
                    valueProviderCallback: _ => interruptEnable,
                    writeCallback: (_, value) => { interruptEnable |= (uint)value & EventMask; UpdateInterrupts(); });

            Registers.IntenClr.Define(this)
                .WithValueField(0, 32, name: "INTENCLR",
                    valueProviderCallback: _ => interruptEnable,
                    writeCallback: (_, value) => { interruptEnable &= ~(uint)value; UpdateInterrupts(); });

            // MICSTATUS (CCM) / STATUS (AAR) — same offset, meaning per ENABLE
            Registers.MicStatus.Define(this)
                .WithValueField(0, 4, FieldMode.Read, name: "MICSTATUS/STATUS",
                    valueProviderCallback: _ => Personality == Function.Aar ? aarStatus : (micStatusOk ? 1u : 0u))
                .WithReservedBits(4, 28);

            Registers.Enable.Define(this)
                .WithValueField(0, 2, out enable, name: "ENABLE", writeCallback: (_, value) =>
                {
                    if(value != 0 && value != (uint)Function.Ccm && value != (uint)Function.Aar)
                    {
                        this.Log(LogLevel.Warning, "UNSUPPORTED periph={0} what=ENABLE detail=reserved value {1} (0=Disabled, 2=CCM, 3=AAR)", LabelForLog, value);
                    }
                })
                .WithReservedBits(2, 30);

            // MODE (CCM) / NIRK (AAR) — shared flops, reset 0x1 in both views
            Registers.Mode.Define(this, 0x00000001)
                .WithValueField(0, 32, out modeOrNirk, name: "MODE/NIRK");

            Registers.CnfPtr.Define(this)
                .WithValueField(0, 32, out cnfOrIrkPointer, name: "CNFPTR/IRKPTR");

            Registers.InPtr.Define(this)
                .WithValueField(0, 32, out inPointer, name: "INPTR");

            Registers.OutPtr.Define(this)
                .WithValueField(0, 32, out outOrAddrPointer, name: "OUTPTR/ADDRPTR");

            Registers.ScratchPtr.Define(this)
                .WithValueField(0, 32, out scratchPointer, name: "SCRATCHPTR");

            Registers.MaxPacketSize.Define(this, 0x000000FB)
                .WithValueField(0, 8, out maxPacketSize, name: "MAXPACKETSIZE")
                .WithReservedBits(8, 24);

            Registers.RateOverride.Define(this)
                .WithValueField(0, 2, out rateOverride, name: "RATEOVERRIDE")
                .WithReservedBits(2, 30);

            Registers.HeaderMask.Define(this, 0x000000E3)
                .WithValueField(0, 8, out headerMask, name: "HEADERMASK")
                .WithReservedBits(8, 24);
        }

        private void DefineSubscribe(Registers register, string name, DPPISubscribeEndpoint endpoint)
        {
            register.Define(this, name: name)
                .WithValueField(0, 32, name: name,
                    valueProviderCallback: _ => endpoint.RegisterValue,
                    writeCallback: (_, value) => endpoint.RegisterValue = (uint)value);
        }

        // ------------------------- tasks -------------------------

        private void TaskKsgenOrAarStart()
        {
            switch(Personality)
            {
            case Function.Ccm:
                // Keystream generation is not observable architecturally
                // (scratch only); completes synchronously in virtual time.
                SetEvent(Event.EndKsgenOrEnd);
                if(shortEndKsgenCrypt.Value)
                {
                    TaskCrypt();
                }
                break;
            case Function.Aar:
                StartAarResolution();
                break;
            default:
                this.Log(LogLevel.Noisy, "TASKS_KSGEN/START while ENABLE={0}, ignored", enable.Value);
                break;
            }
        }

        private void TaskCrypt()
        {
            if(Personality != Function.Ccm)
            {
                this.Log(LogLevel.Noisy, "TASKS_CRYPT while ENABLE={0}, ignored", enable.Value);
                return;
            }
            RunCrypt();
        }

        private void TaskStop()
        {
            if(Personality == Function.Aar && aarPendingValid)
            {
                // PS: "AAR will generate an END event after it has stopped"
                aarTimer.Enabled = false;
                aarPendingValid = false;
                SetEvent(Event.EndKsgenOrEnd);
                return;
            }
            // CCM operations complete synchronously — nothing in flight
        }

        private void TaskRateOverride()
        {
            if(!rateOverrideWarned)
            {
                rateOverrideWarned = true;
                this.Log(LogLevel.Warning, "UNSUPPORTED periph={0} what=TASKS_RATEOVERRIDE detail=data rate has no effect in this model (crypto completes synchronously)", LabelForLog);
            }
        }

        // ------------------------- CCM -------------------------

        private void RunCrypt()
        {
            var cnf = sysbus.ReadBytes(cnfOrIrkPointer.Value, 33);
            var key = new byte[16];
            Array.Copy(cnf, 0, key, 0, 16);
            var nonce = new byte[13];
            nonce[0] = cnf[16];
            nonce[1] = cnf[17];
            nonce[2] = cnf[18];
            nonce[3] = cnf[19];
            nonce[4] = (byte)((cnf[20] & 0x7F) | ((cnf[24] & 1) << 7));
            Array.Copy(cnf, 25, nonce, 5, 8);

            var raw = (uint)modeOrNirk.Value;
            var decrypt = (raw & 1) != 0;
            var lengthExtended = ((raw >> 24) & 1) != 0;
            var maxPayload = lengthExtended ? (int)maxPacketSize.Value : DefaultModeMaxPayload;

            var inHeader = sysbus.ReadBytes(inPointer.Value, 3);
            var header = inHeader[0];
            int length = inHeader[1];
            var rfu = inHeader[2];
            var aad = new byte[] { (byte)(header & (byte)headerMask.Value) };

            if(length == 0)
            {
                // moved through unmodified; decryption always passes the MIC check
                sysbus.WriteBytes(new[] { header, (byte)0, rfu }, outOrAddrPointer.Value);
                if(decrypt)
                {
                    micStatusOk = true;
                }
                SetEvent(Event.EndCryptOrResolved);
                return;
            }

            if(!decrypt)
            {
                if(length > maxPayload)
                {
                    this.Log(LogLevel.Warning, "UNSUPPORTED periph={0} what=ccm-length detail=payload {1} exceeds keystream capacity {2} (MODE.LENGTH={3}), clamping", LabelForLog, length, maxPayload, lengthExtended ? "Extended" : "Default");
                    length = maxPayload;
                }
                var plaintext = sysbus.ReadBytes(inPointer.Value + 3, length);
                var ciphertext = CcmTransform(key, nonce, aad, plaintext, encrypt: true, out var mic);
                var output = new byte[3 + length + MicLength];
                output[0] = header;
                output[1] = (byte)(length + MicLength);
                output[2] = rfu;
                Array.Copy(ciphertext, 0, output, 3, length);
                Array.Copy(mic, 0, output, 3 + length, MicLength);
                sysbus.WriteBytes(output, outOrAddrPointer.Value);
                this.Log(LogLevel.Noisy, "CCM encrypt: {0} payload bytes", length);
            }
            else
            {
                if(length < 5)
                {
                    // PS: decryptable packets are >= 5 bytes; 1..4 fail the MIC check
                    micStatusOk = false;
                    sysbus.WriteBytes(new[] { header, (byte)0, rfu }, outOrAddrPointer.Value);
                    SetEvent(Event.EndCryptOrResolved);
                    return;
                }
                var payloadLength = length - MicLength;
                if(payloadLength > maxPayload)
                {
                    this.Log(LogLevel.Warning, "UNSUPPORTED periph={0} what=ccm-length detail=payload {1} exceeds keystream capacity {2}, clamping", LabelForLog, payloadLength, maxPayload);
                    payloadLength = maxPayload;
                }
                var ciphertext = sysbus.ReadBytes(inPointer.Value + 3, payloadLength);
                var receivedMic = sysbus.ReadBytes(inPointer.Value + 3 + (ulong)payloadLength, MicLength);
                var plaintext = CcmTransform(key, nonce, aad, ciphertext, encrypt: false, out var expectedMic);
                var micOk = true;
                for(var i = 0; i < MicLength; i++)
                {
                    micOk &= expectedMic[i] == receivedMic[i];
                }
                if(FaultMicError)
                {
                    this.Log(LogLevel.Warning, "FaultMicError active: forcing MIC check failure");
                    FaultMicError = false;
                    micOk = false;
                }
                micStatusOk = micOk;
                var output = new byte[3 + payloadLength];
                output[0] = header;
                output[1] = (byte)payloadLength;
                output[2] = rfu;
                Array.Copy(plaintext, 0, output, 3, payloadLength);
                sysbus.WriteBytes(output, outOrAddrPointer.Value);
                this.Log(LogLevel.Noisy, "CCM decrypt: {0} payload bytes, MIC {1}", payloadLength, micOk ? "ok" : "FAILED");
            }
            SetEvent(Event.EndCryptOrResolved);
        }

        // AES-CCM per RFC 3610 with L=2, M=4, 13-byte nonce (the Bluetooth LE
        // link-layer parameterisation, BT Core Vol 6 Part E). Returns the
        // transformed payload; mic is the (encrypted) MIC. For decryption the
        // MIC is computed over the recovered plaintext.
        private static byte[] CcmTransform(byte[] key, byte[] nonce, byte[] aad, byte[] data, bool encrypt, out byte[] mic)
        {
            using(var aes = AesProvider.GetEcbProvider(key))
            {
                Func<byte[], byte[]> cipher = input =>
                {
                    var block = new byte[16];
                    Array.Copy(input, block, 16);
                    aes.EncryptBlockInSitu(Block.UsingBytes(block));
                    return block;
                };

                // Counter blocks A_i = 0x01 || nonce || i
                Func<int, byte[]> counterBlock = index =>
                {
                    var block = new byte[16];
                    block[0] = 0x01; // flags: L-1
                    Array.Copy(nonce, 0, block, 1, 13);
                    block[14] = (byte)(index >> 8);
                    block[15] = (byte)index;
                    return block;
                };

                // CTR transform of the payload (S_1..)
                var output = new byte[data.Length];
                for(var i = 0; i < data.Length; i += 16)
                {
                    var keystream = cipher(counterBlock(i / 16 + 1));
                    for(var j = i; j < Math.Min(i + 16, data.Length); j++)
                    {
                        output[j] = (byte)(data[j] ^ keystream[j - i]);
                    }
                }
                var plaintext = encrypt ? data : output;

                // CBC-MAC over B_0 || AAD block || plaintext blocks
                var b0 = new byte[16];
                b0[0] = 0x49; // flags: Adata | ((M-2)/2)<<3 | (L-1)
                Array.Copy(nonce, 0, b0, 1, 13);
                b0[14] = (byte)(plaintext.Length >> 8);
                b0[15] = (byte)plaintext.Length;
                var x = cipher(b0);

                var aadBlock = new byte[16];
                aadBlock[0] = 0;
                aadBlock[1] = (byte)aad.Length;
                Array.Copy(aad, 0, aadBlock, 2, aad.Length);
                for(var i = 0; i < 16; i++)
                {
                    aadBlock[i] ^= x[i];
                }
                x = cipher(aadBlock);

                for(var i = 0; i < plaintext.Length; i += 16)
                {
                    var block = new byte[16];
                    for(var j = i; j < Math.Min(i + 16, plaintext.Length); j++)
                    {
                        block[j - i] = plaintext[j];
                    }
                    for(var j = 0; j < 16; j++)
                    {
                        block[j] ^= x[j];
                    }
                    x = cipher(block);
                }

                var s0 = cipher(counterBlock(0));
                mic = new byte[MicLength];
                for(var i = 0; i < MicLength; i++)
                {
                    mic[i] = (byte)(x[i] ^ s0[i]);
                }
                return output;
            }
        }

        // ------------------------- AAR -------------------------

        private void StartAarResolution()
        {
            var nirk = (int)(modeOrNirk.Value & 0x1F);
            if(nirk < 1)
            {
                nirk = 1;
            }
            if(nirk > 16)
            {
                nirk = 16;
            }
            var resolution = aar.Resolve(sysbus, cnfOrIrkPointer.Value, outOrAddrPointer.Value, nirk);
            aarPending = resolution;
            aarPendingValid = true;
            aarTimer.Limit = (ulong)Math.Max(1, Math.Round(resolution.DurationUs * TicksPerMicrosecond));
            aarTimer.Value = 0;
            aarTimer.Enabled = true;
        }

        private void CompleteAarResolution()
        {
            if(!aarPendingValid)
            {
                return;
            }
            aarPendingValid = false;
            if(aarPending.Resolved)
            {
                aarStatus = (uint)aarPending.Index;
                SetEvent(Event.EndCryptOrResolved);
            }
            else
            {
                SetEvent(Event.ErrorOrNotResolved);
            }
            SetEvent(Event.EndKsgenOrEnd);
        }

        // ------------------------- plumbing -------------------------

        private void SetEvent(Event @event)
        {
            eventPending |= 1u << (int)@event;
            publishEvent[(int)@event].Publish();
            UpdateInterrupts();
        }

        private void UpdateInterrupts()
        {
            var asserted = (eventPending & interruptEnable) != 0;
            if(asserted && !IRQ.IsSet && FaultDropInterrupt)
            {
                FaultDropInterrupt = false;
                this.Log(LogLevel.Warning, "FaultDropInterrupt active: swallowing IRQ assertion");
                return;
            }
            IRQ.Set(asserted);
        }

        private Function Personality => (Function)(uint)enable.Value;

        private string LabelForLog
        {
            get
            {
                try
                {
                    if(machine.TryGetLocalName(this, out var name))
                    {
                        return name;
                    }
                }
                catch(Exception)
                {
                    // registration not finished yet — fall through
                }
                return GetType().Name;
            }
        }

        private uint eventPending;
        private uint interruptEnable;
        private bool micStatusOk;
        private uint aarStatus;
        private AarResolution aarPending;
        private bool aarPendingValid;
        private bool rateOverrideWarned;

        private IValueRegisterField enable;
        private IValueRegisterField modeOrNirk;
        private IValueRegisterField cnfOrIrkPointer;
        private IValueRegisterField inPointer;
        private IValueRegisterField outOrAddrPointer;
        private IValueRegisterField scratchPointer;
        private IValueRegisterField maxPacketSize;
        private IValueRegisterField rateOverride;
        private IValueRegisterField headerMask;
        private IFlagRegisterField shortEndKsgenCrypt;

        private readonly NRF5340_AAR aar;
        private readonly DPPISubscribeEndpoint subscribeKsgenOrStart;
        private readonly DPPISubscribeEndpoint subscribeCrypt;
        private readonly DPPISubscribeEndpoint subscribeStop;
        private readonly DPPISubscribeEndpoint subscribeRateOverride;
        private readonly DPPIPublishEndpoint[] publishEvent;
        private readonly LimitTimer aarTimer;

        private static readonly string[] EventNames =
        {
            "EVENTS_ENDKSGEN/END",
            "EVENTS_ENDCRYPT/RESOLVED",
            "EVENTS_ERROR/NOTRESOLVED",
        };

        private const int EventCount = 3;
        private const uint EventMask = 0x7;
        private const int MicLength = 4;
        private const int DefaultModeMaxPayload = 27;
        private const long TimerFrequency = 16000000;
        private const double TicksPerMicrosecond = 16;

        private enum Function
        {
            Disabled = 0,
            Ccm = 2,
            Aar = 3,
        }

        private enum Event
        {
            EndKsgenOrEnd = 0,
            EndCryptOrResolved = 1,
            ErrorOrNotResolved = 2,
        }

        private enum Registers : long
        {
            TasksKsgen = 0x000,          // CCM TASKS_KSGEN / AAR TASKS_START
            TasksCrypt = 0x004,          // CCM only
            TasksStop = 0x008,           // both
            TasksRateOverride = 0x00C,   // CCM only
            SubscribeKsgen = 0x080,
            SubscribeCrypt = 0x084,
            SubscribeStop = 0x088,
            SubscribeRateOverride = 0x08C,
            EventsEndKsgen = 0x100,      // CCM ENDKSGEN / AAR END
            EventsEndCrypt = 0x104,      // CCM ENDCRYPT / AAR RESOLVED
            EventsError = 0x108,         // CCM ERROR / AAR NOTRESOLVED
            PublishEndKsgen = 0x180,
            PublishEndCrypt = 0x184,
            PublishError = 0x188,
            Shorts = 0x200,
            IntenSet = 0x304,
            IntenClr = 0x308,
            MicStatus = 0x400,           // CCM MICSTATUS / AAR STATUS
            Enable = 0x500,
            Mode = 0x504,                // CCM MODE / AAR NIRK
            CnfPtr = 0x508,              // CCM CNFPTR / AAR IRKPTR
            InPtr = 0x50C,               // CCM only
            OutPtr = 0x510,              // CCM OUTPTR / AAR ADDRPTR
            ScratchPtr = 0x514,          // both
            MaxPacketSize = 0x518,       // CCM only
            RateOverride = 0x51C,        // CCM only
            HeaderMask = 0x520,          // CCM only
        }
    }
}
